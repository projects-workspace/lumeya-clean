const LUMEYA_LANGUAGE_KEY = 'language';
const LUMEYA_LEGACY_LANGUAGE_KEY = 'lumeya-language';
const LUMEYA_SUPPORTED_LANGS = ['en', 'cz', 'ru', 'ua'];
const LUMEYA_DEFAULT_LANG = 'en';

function getPreferredLanguage() {
  return LUMEYA_DEFAULT_LANG;
}

function persistLanguage() {
  localStorage.setItem(LUMEYA_LANGUAGE_KEY, LUMEYA_DEFAULT_LANG);
  localStorage.setItem(LUMEYA_LEGACY_LANGUAGE_KEY, LUMEYA_DEFAULT_LANG);
}

window.applyTranslations = function(lang) {
  const safeLang = LUMEYA_DEFAULT_LANG;
  const t = translations[safeLang] || translations[LUMEYA_DEFAULT_LANG];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      el.textContent = t[key];
    }
  });
}

// Initialize language
document.addEventListener('DOMContentLoaded', () => {
  const currentLang = getPreferredLanguage();
  persistLanguage(currentLang);
  document.documentElement.lang = LUMEYA_DEFAULT_LANG;
  window.applyTranslations(currentLang);

  // Highlight active lang button in ALL language switchers
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === currentLang);
  });
});

// Setup lang switchers globally
document.addEventListener('click', (e) => {
  if (e.target.classList.contains('lang-btn')) {
    persistLanguage(LUMEYA_DEFAULT_LANG);
    window.applyTranslations(LUMEYA_DEFAULT_LANG);

    // Update active UI in ALL lang switchers
    document.querySelectorAll('.lang-btn').forEach(b => {
      b.classList.toggle('active', b.dataset.lang === LUMEYA_DEFAULT_LANG);
    });
  }
});
